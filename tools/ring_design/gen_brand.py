"""Генератор токенів «Рингу».

Єдине джерело: docs/ring/design/brand_tokens.json (власник — арт-директор).
Видає (вручну не правити):
  Assets/_Project/Scripts/Gameplay/Ring/Models/BrandTokens.cs  — чистий C# без UnityEngine (тестується headless)
  Assets/_Project/Scripts/Gameplay/Ring/UI/RingTheme.cs        — Color-обгортка для Unity
  tools/blender/ring_brand.py                                  — палітра для скриптів Blender/PIL
  docs/ring/design/brand_tokens.css                            — змінні CSS для дошки й HTML-ескізів

Запуск: python tools/ring_design/gen_brand.py   (лише стандартна бібліотека; ідемпотентний)
Перевірка синхронності: RingDesignGuardTests.BrandTokens_MatchJson.
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "docs", "ring", "design", "brand_tokens.json")
OUT_MODEL = os.path.join(ROOT, "Assets", "_Project", "Scripts", "Gameplay", "Ring", "Models", "BrandTokens.cs")
OUT_THEME = os.path.join(ROOT, "Assets", "_Project", "Scripts", "Gameplay", "Ring", "UI", "RingTheme.cs")
OUT_PY = os.path.join(ROOT, "tools", "blender", "ring_brand.py")
OUT_CSS = os.path.join(ROOT, "docs", "ring", "design", "brand_tokens.css")

HEADER_CS = ("// <auto-generated>\n"
             "// tools/ring_design/gen_brand.py з docs/ring/design/brand_tokens.json. Вручну не правити:\n"
             "// палітра й кегль належать арт-директору, зміни — через токени (docs/ring/DESIGN_SYSTEM.md).\n"
             "// </auto-generated>\n")


def pascal(name):
    return name[0].upper() + name[1:]


def hex_to_int(h):
    return int(h.lstrip("#"), 16)


def hex_to_rgb(h):
    v = hex_to_int(h)
    return (v >> 16) & 255, (v >> 8) & 255, v & 255


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def fl(x):
    s = repr(float(x))
    return s + "f"


def gen_model(t):
    lines = [HEADER_CS,
             "namespace Game.Gameplay.Ring.Models",
             "{",
             "    /// <summary>",
             "    /// Токени вигляду «Рингу» без UnityEngine: кольори RGB (0xRRGGBB), прозорості, кегль (в одиницях еталона 900 px висоти),",
             "    /// простір і рух. Єдине джерело — docs/ring/design/brand_tokens.json; власник палітри — арт-директор.",
             "    /// </summary>",
             "    public static class BrandTokens",
             "    {"]
    lines.append("        // ---- кольори (сирі) ----")
    for k, v in t["colors"].items():
        lines.append("        public const uint %s = 0x%06X;" % (pascal(k), hex_to_int(v)))
    lines.append("")
    lines.append("        // ---- прозорості ----")
    for k, v in t["alpha"].items():
        lines.append("        public const float Alpha%s = %s;" % (pascal(k), fl(v)))
    lines.append("")
    lines.append("        // ---- кегль (еталон %d px висоти екрана) ----" % t["type"]["refHeight"])
    lines.append("        public const int TypeRefHeight = %d;" % t["type"]["refHeight"])
    lines.append("        /// <summary>Найменший кегль для інформації, за якою гравець діє (XAG: ≥18 px @1080p = 15 px @900).</summary>")
    lines.append("        public const int TypeMinInfo = %d;" % t["type"]["minInfo"])
    for k, v in t["type"]["sizes"].items():
        lines.append("        public const int Type%s = %d;" % (pascal(k), v))
    for k, v in t["type"]["stinger"].items():
        lines.append("        public const int Stinger%s = %d;" % (pascal(k), v))
    lines.append("")
    lines.append("        // ---- простір ----")
    for k, v in t["space"].items():
        lines.append("        public const int Space%s = %d;" % (pascal(k), v))
    lines.append("")
    lines.append("        // ---- рух ----")
    for k, v in t["motion"].items():
        if isinstance(v, float) and not float(v).is_integer():
            lines.append("        public const float Motion%s = %s;" % (pascal(k), fl(v)))
        else:
            lines.append("        public const int Motion%s = %d;" % (pascal(k), int(v)))
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_theme(t):
    lines = [HEADER_CS,
             "using Game.Gameplay.Ring.Models;",
             "using UnityEngine;",
             "",
             "namespace Game.Gameplay.Ring.UI",
             "{",
             "    /// <summary>",
             "    /// Тема «Рингу»: кольори з токенів арт-директора (Color-обгортка над <see cref=\"BrandTokens\"/>).",
             "    /// Нових кольорів у коді не вигадувати: брати звідси або просити в арт-директора (Статут вигляду, COL-01).",
             "    /// </summary>",
             "    public static class RingTheme",
             "    {",
             "        public static Color Rgb(uint rgb, float a = 1f)",
             "        {",
             "            return new Color(((rgb >> 16) & 255u) / 255f, ((rgb >> 8) & 255u) / 255f, (rgb & 255u) / 255f, a);",
             "        }",
             "",
             "        public static Color WithAlpha(Color c, float a)",
             "        {",
             "            return new Color(c.r, c.g, c.b, a);",
             "        }",
             "",
             "        /// <summary>",
             "        /// ВЕЛИКІ літери для ролі display (Fira Sans Extra Condensed): мітки, імена й виноски — ВЕЛИКИМИ (Статут вигляду,",
             "        /// TYPE-02/TYPE-03). До 08.11.2026 display була Sofia Sans з болгарськими малими й гостроверхою «Л» — замінено.",
             "        /// </summary>",
             "        public static string Caps(string s)",
             "        {",
             "            return s == null ? null : s.ToUpperInvariant();",
             "        }",
             "",
             "        // ---- сирі ----"]
    for k in t["colors"]:
        lines.append("        public static readonly Color %s = Rgb(BrandTokens.%s);" % (pascal(k), pascal(k)))
    lines.append("")
    lines.append("        // ---- ролі (колір = сенс; один колір — один сенс, Статут COL-02) ----")
    for k, v in t["roles"].items():
        lines.append("        public static readonly Color %s = %s;" % (pascal(k), pascal(v)))
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_py(t):
    out = ['# -*- coding: utf-8 -*-',
           '"""Палітра «Рингу» для скриптів Blender/PIL. Згенеровано tools/ring_design/gen_brand.py',
           'з docs/ring/design/brand_tokens.json. Вручну не правити: нові кольори — через арт-директора."""',
           '',
           'HEX = {']
    for k, v in t["colors"].items():
        out.append("    %r: %r," % (k, v.upper()))
    out.append("}")
    out.append("")
    out.append("COLORS = {")
    for k, v in t["colors"].items():
        out.append("    %r: %r," % (k, hex_to_rgb(v)))
    out.append("}")
    out.append("")
    out.append("ROLES = {")
    for k, v in t["roles"].items():
        out.append("    %r: %r," % (k, v))
    out.append("}")
    out.append("")
    out.append("ALPHA = {")
    for k, v in t["alpha"].items():
        out.append("    %r: %r," % (k, v))
    out.append("}")
    out.append("""

def rgb(name):
    \"\"\"Колір (R, G, B) 0..255; name — сирий токен або роль.\"\"\"
    return COLORS[ROLES.get(name, name)]


def rgba(name, a=255):
    r, g, b = rgb(name)
    return (r, g, b, int(a))


def hexstr(name):
    return HEX[ROLES.get(name, name)]


def _lin(c):
    c = c / 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def linear_rgba(name, a=1.0):
    \"\"\"Лінійний RGBA 0..1 для вузлів матеріалів Blender (sRGB → лінійний).\"\"\"
    r, g, b = rgb(name)
    return (_lin(r), _lin(g), _lin(b), a)
""")
    return "\n".join(out) + "\n"


def gen_css(t):
    out = ["/* Згенеровано tools/ring_design/gen_brand.py з brand_tokens.json. Вручну не правити. */", ":root {"]
    for k, v in t["colors"].items():
        out.append("  --%s: %s;" % (k, v.upper()))
    for k, v in t["roles"].items():
        out.append("  --role-%s: var(--%s);" % (k, v))
    for k, v in t["alpha"].items():
        out.append("  --alpha-%s: %s;" % (k, v))
    for k, v in t["type"]["sizes"].items():
        out.append("  --size-%s: %dpx;" % (k, v))
    for k, v in t["type"]["stinger"].items():
        out.append("  --stinger-%s: %dpx;" % (k, v))
    for k, v in t["space"].items():
        unit = "deg" if k == "slantDeg" else ("" if k == "unit" else "px")
        out.append("  --space-%s: %s%s;" % (k, v, unit))
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    with open(SRC, "r", encoding="utf-8") as f:
        t = json.load(f)
    # цілісність: ролі посилаються на наявні сирі кольори
    for role, raw in t["roles"].items():
        if raw not in t["colors"]:
            sys.exit("роль %s посилається на невідомий колір %s" % (role, raw))
    write(OUT_MODEL, gen_model(t))
    write(OUT_THEME, gen_theme(t))
    write(OUT_PY, gen_py(t))
    write(OUT_CSS, gen_css(t))
    print("ok: %d кольорів, %d ролей" % (len(t["colors"]), len(t["roles"])))


if __name__ == "__main__":
    main()
