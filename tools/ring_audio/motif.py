"""Лейтмотив і гармонія меню «Рингу» як дані. Власний оригінальний матеріал.

Напрям (рішення власника 07–08.11.2026): брутально, похмуро, без радості.
Тональність — мі мінор / мі фрігійський (F = ♭2 для загрози; B♭ — тритон).
Гармонія — силові акорди (корінь + квінта + октава), без терцій і джазових розширень.
Розмір 4/4, 16 кроків (шістнадцятих) на такт. Номери тактів тут 0-based
(у документації — 1-based).
"""

KEY_NAME = "мі мінор / мі фрігійський (E minor / Phrygian)"
KEY_SHORT = "Em"

NAMES = ["C", "Db", "D", "Eb", "E", "F", "Gb", "G", "Ab", "A", "Bb", "B"]


def name(m):
    return f"{NAMES[m % 12]}{m // 12 - 1}"


# Корені силових акордів (MIDI, C4 = 60): E2 F2 G2 B♭2
ROOTS = {"E": 40, "F": 41, "G": 43, "Bb": 46}


def chord_at(bar, step=0):
    """Гармонія 4-тактового кола: такт1 E5 | такт2 E5 -> F5 (3-я доля) |
    такт3 G5 -> F5 | такт4 E5 зі штихом B♭5 на останній восьмій (кроки 14-15)."""
    k = bar % 4
    if k == 0:
        return "E"
    if k == 1:
        return "E" if step < 8 else "F"
    if k == 2:
        return "G" if step < 8 else "F"
    return "Bb" if step >= 14 else "E"


def power(name_, octave=0, wide=True):
    """Силовий акорд: корінь, квінта, октава (MIDI)."""
    r = ROOTS[name_] + 12 * octave
    return (r, r + 7, r + 12) if wide else (r, r + 7)


def chord_at_slow(bar, step=0):
    """Те саме коло, розтягнуте удвічі (settings): акорд на 2 такти."""
    return chord_at(bar // 2, (bar % 2) * 8 + step // 2)


