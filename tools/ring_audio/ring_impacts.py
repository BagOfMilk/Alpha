# ---------------------------------------------------------------- полотно
class C:
    def __init__(s, dur, seed):
        s.n = int(dur * SR)
        s.y = np.zeros(s.n)
        s.seed = seed
        s.k = 0

    def sd(s):
        s.k += 1
        return s.seed * 1009 + s.k

    def add(s, x, t=0.0, g=1.0):
        i = int(t * SR)
        if i >= s.n or len(x) == 0:
            return
        x = np.array(x, dtype=float)
        f = min(len(x) // 3, int(0.025 * SR))
        if f > 8:
            x[-f:] *= np.cos(np.linspace(0, np.pi / 2, f)) ** 2
        m = min(len(x), s.n - i)
        s.y[i:i + m] += x[:m] * g


def N(n, seed):
    return np.random.default_rng(seed).standard_normal(n)


def pk(x):
    m = np.max(np.abs(x))
    return x / m if m > 1e-12 else x


def bn(n, seed, lo=None, hi=None, order=2):
    x = N(n, seed)
    if lo:
        x = filt(x, "hp", lo, 0.7, order)
    if hi:
        x = filt(x, "lp", hi, 0.7, order)
    return x


def env(n, att_ms, tau_ms):
    t = np.arange(n) / SR
    ta, td = max(att_ms, 0.1) / 1000, tau_ms / 1000
    e = (1 - np.exp(-t / ta)) * np.exp(-t / td)
    return e / max(e.max(), 1e-9)


# ---------------------------------------------------------------- будівельні блоки
def slap(c, t=0.0, g=1.0, lo=1500, hi=6000, tau=5.0, att=0.4, dur=0.06):
    """ляпас шкіри/полотна: широкосмуговий шум, різка атака"""
    n = int(dur * SR)
    x = pk(bn(n, c.sd(), lo, hi)) * env(n, att, tau)
    c.add(x, t, g)


def meat(c, t=0.0, g=1.0, lo=80, hi=280, tau=45.0, att=1.0, dur=0.3):
    """глухий м'ясний удар 60-300 Гц, швидко згасає"""
    n = int(dur * SR)
    x = pk(bn(n, c.sd(), lo, hi)) * env(n, att, tau)
    c.add(x, t, g)


def knock(c, t=0.0, g=0.3, lo=400, hi=1400, tau=10.0):
    """кістка/щільна маса: середина, дуже коротка (не дзвенить)"""
    n = int(0.08 * SR)
    c.add(pk(bn(n, c.sd(), lo, hi)) * env(n, 0.5, tau), t, g)


def body(c, t=0.0, g=1.0, s=1.0, m=1.0, k=0.3, slo=1500, shi=6000, stau=5.0,
         mlo=80, mhi=280, mtau=45.0):
    slap(c, t, g * s, slo, shi, stau)
    meat(c, t, g * m, mlo, mhi, mtau)
    knock(c, t, g * k)


def boom(c, t=0.0, g=1.0, w=14.0, low=1.0, tau=1.0, dur=0.7, noise=0.5, seed=None):
    """піднятий поміст як барабан: низькодобротні моди 38-100 і 120-320 Гц, збуджені силою (підвищений косинус w мс)."""
    r = np.random.default_rng(seed if seed is not None else c.sd())
    n = int(dur * SR)
    tt = np.arange(n) / SR
    ir = np.zeros(n)
    for f in np.geomspace(38, 100, 7) * low * r.uniform(0.93, 1.07, 7):
        tau_k = r.uniform(0.05, 0.10) * tau * (70 / f) ** 0.4
        ir += r.uniform(0.6, 1.0) * np.exp(-tt / tau_k) * np.sin(2 * np.pi * f * tt + r.uniform(0, 6.28))
    for f in np.geomspace(120, 330, 10) * low * r.uniform(0.92, 1.08, 10):
        tau_k = r.uniform(0.025, 0.06) * tau
        ir += 0.35 * r.uniform(0.4, 1.0) * np.exp(-tt / tau_k) * np.sin(2 * np.pi * f * tt + r.uniform(0, 6.28))
    nz = bn(n, c.sd(), 35, 260) * np.exp(-tt / (0.11 * tau))
    ir = pk(ir) + noise * pk(nz)
    wn = max(int(w * SR / 1000), 4)
    force = 0.5 * (1 - np.cos(np.linspace(0, 2 * np.pi, wn)))
    L = n + wn
    out = np.fft.irfft(np.fft.rfft(ir, L) * np.fft.rfft(force, L), L)[:n]
    c.add(pk(out), t, g)


def sub(c, t=0.0, g=1.0, lo=28, hi=62, tau=300.0, dur=0.8):
    n = int(dur * SR)
    c.add(pk(bn(n, c.sd(), lo, hi, 3)) * env(n, 4.0, tau), t, g)


def rattle(c, t0, t1, count, g=0.2, dur=0.12):
    """брязкіт рами/стяжок: короткі пачки негармонійних мод 2-7 кГц"""
    r = np.random.default_rng(c.sd())
    n = int(dur * SR)
    tt = np.arange(n) / SR
    for _ in range(count):
        ts = r.uniform(t0, t1)
        x = np.zeros(n)
        for f in r.uniform(1800, 7500, 6):
            x += r.uniform(0.3, 1) * np.exp(-tt / r.uniform(0.002, 0.009)) * np.sin(2 * np.pi * f * tt + r.uniform(0, 6.28))
        x = pk(x) + 0.9 * pk(bn(n, c.sd(), 1800, 8000, 1)) * np.exp(-tt / 0.004)
        x *= 1 - np.exp(-tt / 0.0004)
        c.add(pk(x), ts, g * r.uniform(0.3, 1.0) * np.exp(-(ts - t0) / max(t1 - t0, .05) * 0.8))


def rub(c, t=0.0, dur=0.15, g=0.15, lo=300, hi=4000, rate=22.0):
    """тертя одягу/шкіри/полотна: шум з повільною нерівною обвідною"""
    n = int(dur * SR)
    x = bn(n, c.sd(), lo, hi, 1)
    m = np.abs(filt(N(n, c.sd()), "lp", rate, 0.7, 2))
    m = m / max(m.max(), 1e-9)
    e = np.sin(np.pi * np.linspace(0, 1, n)) ** 0.7
    c.add(pk(x) * (0.25 + m) * e, t, g)


def whoosh(c, t=0.0, dur=0.05, g=0.2, lo=500, hi=3500):
    n = int(dur * SR)
    e = (np.linspace(0, 1, n)) ** 2
    c.add(pk(bn(n, c.sd(), lo, hi)) * e, t, g)


def tail(c, t=0.0, dur=0.6, g=0.15, lo=60, hi=700, tau=250.0):
    n = int(dur * SR)
    c.add(pk(bn(n, c.sd(), lo, hi)) * env(n, 6.0, tau), t, g)


def creak(c, t0, t1, count, lo, hi, g=0.2, tau=(4, 22), burst=(2, 6), gap=(0.006, 0.018), q=3.0):
    """стик-сліп: кластери коротких тертєвих імпульсів із випадковою центральною частотою (без плавної висоти)"""
    r = np.random.default_rng(c.sd())
    for _ in range(count):
        ts = r.uniform(t0, t1)
        fc = float(np.exp(r.uniform(np.log(lo), np.log(hi))))
        for _ in range(int(r.integers(burst[0], burst[1] + 1))):
            n = int(r.uniform(*tau) * 3 / 1000 * SR) + 64
            x = filt(N(n, c.sd()), "bp", fc * r.uniform(0.9, 1.12), q, 1)
            x = pk(x) * env(n, 0.3, r.uniform(*tau))
            c.add(x, ts, g * r.uniform(0.3, 1.0))
            ts += r.uniform(*gap)


def swell(c, t0, t1, g, lo, hi, peak=0.5):
    """повільне наростання тиску: низький шум із вигином навантаження"""
    n = int((t1 - t0) * SR)
    x = pk(bn(n, c.sd(), lo, hi, 2))
    u = np.linspace(0, 1, n)
    e = np.where(u < peak, (u / peak) ** 1.5, 1 - 0.4 * (u - peak) / (1 - peak))
    m = 0.7 + 0.3 * pk(filt(N(n, c.sd()), "lp", 9, 0.7, 2))
    c.add(x * e * m, t0, g)


# ---------------------------------------------------------------- рецепти
R = {}


def rec(slot, dur, level, labels):
    def deco(f):
        R[slot] = (dur, level, labels, f)
        return f
    return deco


