def finish(y, level_db):
    y = filt(y, "hp", 22, 0.7, 1)
    n = len(y)
    f_in = int(0.0004 * SR)
    y[:f_in] *= np.linspace(0, 1, f_in)
    f_out = int(min(0.03, n / SR * 0.12) * SR)
    y[-f_out:] *= np.cos(np.linspace(0, np.pi / 2, f_out)) ** 2
    y = np.tanh(y / max(np.max(np.abs(y)), 1e-9) * 1.15) / np.tanh(1.15)
    y /= max(np.max(np.abs(y)), 1e-9)
    y *= 10 ** (level_db / 20)
    for _ in range(4):
        tp = true_peak_db(y)
        if tp <= -1.05:
            break
        y *= 10 ** ((-1.1 - tp) / 20)
    return y


def write_wav(path, y):
    pcm = np.clip(np.round(y * 32767), -32768, 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


