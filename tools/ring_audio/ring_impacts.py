def spectrogram(y, path, title):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    nfft, hop = 2048, 128
    win = np.hanning(nfft)
    pad = np.concatenate([y, np.zeros(nfft)])
    fr = np.stack([pad[i:i + nfft] * win for i in range(0, len(y), hop)])
    S = 20 * np.log10(np.abs(np.fft.rfft(fr, axis=1)).T / (nfft / 4) + 1e-9)
    fq = np.fft.rfftfreq(nfft, 1 / SR)
    ok = (fq >= 30) & (fq <= 16000)
    tt = np.arange(S.shape[1]) * hop / SR
    fig, ax = plt.subplots(2, 1, figsize=(8, 4.6), gridspec_kw={"height_ratios": [1, 3.2]}, sharex=True)
    ax[0].plot(np.arange(len(y)) / SR, y, lw=0.5, color="k")
    ax[0].set_ylim(-1, 1)
    ax[0].set_title(title, fontsize=9)
    ax[1].pcolormesh(tt, fq[ok], np.clip(S[ok], -90, 0), cmap="magma", vmin=-90, vmax=-10, shading="auto")
    ax[1].set_yscale("log")
    ax[1].set_ylim(30, 16000)
    ax[1].set_xlabel("с")
    ax[1].set_ylabel("Гц")
    ax[1].set_yticks([50, 100, 250, 500, 1000, 2000, 4000, 8000, 16000])
    ax[1].set_yticklabels(["50", "100", "250", "500", "1k", "2k", "4k", "8k", "16k"])
    fig.tight_layout()
    fig.savefig(path, dpi=90)
    plt.close(fig)


def sheet(ids, spec_dir, path, cols=6):
    from PIL import Image
    ims = [Image.open(os.path.join(spec_dir, i + ".png")) for i in ids]
    w, h = 400, 230
    rows = (len(ims) + cols - 1) // cols
    S = Image.new("RGB", (cols * w, rows * h), "white")
    for k, im in enumerate(ims):
        S.paste(im.resize((w, h)), ((k % cols) * w, (k // cols) * h))
    S.save(path)


