namespace Game.Core.Stats
{
    /// <summary>
    /// Четыре атрибута персонажа (GDD §2.1). Почти статичная база: задаются при
    /// создании, в уровнях НЕ растут — поднять можно только крафтом аугмента в
    /// Лаборатории (опционально, редко; см. Эпик 6). Атрибуты задают производные
    /// числа (<see cref="DerivedStat"/>) и дают флэт к проверкам (<see cref="SkillType"/>-проверки).
    ///
    /// Правило «один эффект — одна система»: атрибуты модификаторами не трогаются,
    /// модификаторы живут только на производных статах.
    /// </summary>
    public enum AttributeType
    {
        None = 0,
        Strength = 1, // Сила    — HP, перенос, урон ближнего, силовой подход в Запугивании
        Agility = 2,  // Ловкость — AP, точность, защита, инициатива, крит
        Wits = 3,     // Смекалка — инициатива, Убеждение/Торговля, утилита
        Will = 4      // Воля    — сопротивление состояниям (Resolve), волевой подход в Запугивании
    }
}
