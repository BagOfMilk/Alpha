namespace Game.Core.Stats
{
    /// <summary>
    /// Все характеристики персонажа в одном перечне. Делятся на три группы:
    /// боевые (используются в XCOM-бою), способности-склонности (используются
    /// при назначении на позиции базы) и производные/ресурсные.
    ///
    /// Хранение через единый enum + <see cref="StatBlock"/> делает систему
    /// data-driven: формулы боя и производства просто ссылаются на нужный стат,
    /// а баланс крутится числами, без правки кода.
    /// </summary>
    public enum StatType
    {
        None = 0,

        // ---- Боевые (XCOM-style) ----
        Health = 1,        // запас здоровья (HP)
        Aim = 2,           // меткость, базовый % попадания
        Defense = 3,       // снижение шанса попасть по юниту
        Dodge = 4,         // шанс превратить попадание в "grazing"/промах
        Mobility = 5,      // дальность перемещения за одно действие (в тайлах)
        Will = 6,          // воля: сопротивление панике/контролю
        CritChance = 7,    // базовый шанс крита, %
        Armor = 8,         // плоское поглощение урона
        Tech = 9,          // эффективность гаджетов/взлома
        Psi = 10,          // сила пси-способностей

        // ---- Склонности для ролей на базе ----
        Leadership = 20,   // совет, командование, мораль
        Engineering = 21,  // мастерская, строительство, ремонт
        Science = 22,      // лаборатория, исследования
        Medicine = 23,     // лазарет, лечение, скорость восстановления
        Logistics = 24,    // склад/снабжение, эффективность ресурсов
        Charisma = 25,     // поселение, вербовка, торговля, дипломатия
        Scouting = 26,     // разведка, поиск точек вылазок, добыча интела
        Survival = 27      // живучесть в Дажах, снижение риска ранений
    }
}
