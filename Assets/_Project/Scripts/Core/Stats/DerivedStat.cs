namespace Game.Core.Stats
{
    /// <summary>
    /// Производные числа, вычисляемые из атрибутов (<see cref="DerivedStatCalculator"/>)
    /// и модифицируемые гиром / трейтами / шрамами / состояниями / баффами через
    /// ЕДИНЫЙ агрегатор (<see cref="ModifierAggregator"/>, GDD §18 US-18.2).
    ///
    /// Это единственная ось, которую правят модификаторы — атрибуты и скилы
    /// модификаторами не трогаются («один эффект — одна система»). Числа мелкие
    /// (HP ~6–20, AP ~8–10), глубина боя — из способностей/позиции/состояний.
    /// </summary>
    public enum DerivedStat
    {
        None = 0,
        MaxHp = 1,         // запас HP (~6–20)
        ActionPoints = 2,  // пул AP за ход (~8–10)
        Accuracy = 3,      // базовая точность, % (скил оружия добавляется в бою)
        Defense = 4,       // снижает шанс попасть по юниту, %
        Initiative = 5,    // порядок индивидуального хода
        Carry = 6,         // переносимый вес/слоты снаряжения
        CritChance = 7,    // базовый шанс крита, %
        Armor = 8,         // плоское снижение урона за удар (1–2; в осн. от гира)
        Resolve = 9        // сокращение длительности состояний (от Воли)
    }
}
