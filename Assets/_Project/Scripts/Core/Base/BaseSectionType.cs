namespace Game.Core.Base
{
    /// <summary>
    /// Функціональні секції бази. Кожна містить один або кілька слотів
    /// призначення. Рада і Поселення — особливі «соціальні» секції з ТЗ,
    /// решта — виробничі/службові.
    /// </summary>
    public enum BaseSectionType
    {
        None = 0,
        Council = 1,      // рада: стратегічні рішення, мораль, бонуси фракції
        Settlement = 2,   // поселення: населення, їжа, вербування
        Workshop = 3,     // майстерня: матеріали, крафт, лагодження спорядження
        Laboratory = 4,   // лабораторія: дослідження
        Infirmary = 5,    // лазарет: лікування поранених
        Storehouse = 6,   // склад: припаси, логістика
        ScoutingPost = 8, // розвідпост: інтел, відкриття точок вилазок
        Fortifications = 9 // укріплення: варта і дозор, знижують Напругу
        // Barracks (7) прибрана: у списку будівель GDD US-7.1 казарм немає, слотів у
        // неї не було, а «відновлення волі» жодною механікою не підтримано.
        // Дозор переїхав в Укріплення — це будівля з US-7.1, і вона про захист.
    }
}
