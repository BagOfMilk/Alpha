namespace Game.Core.Base
{
    /// <summary>
    /// Функциональные секции базы. Каждая содержит один или несколько слотов
    /// назначения. Совет и Поселение — особые «социальные» секции из ТЗ,
    /// остальные — производственные/служебные.
    /// </summary>
    public enum BaseSectionType
    {
        None = 0,
        Council = 1,      // совет: стратегические решения, мораль, бонусы фракции
        Settlement = 2,   // поселение: население, еда, вербовка
        Workshop = 3,     // мастерская: материалы, крафт, починка снаряжения
        Laboratory = 4,   // лаборатория: исследования
        Infirmary = 5,    // лазарет: лечение раненых
        Storehouse = 6,   // склад: припасы, логистика
        ScoutingPost = 8  // разведпост: интел, открытие точек вылазок
        // Barracks (7) убрана: в списке зданий GDD US-7.1 казармы нет, слотов у
        // неё не было, а «восстановление воли» ни одной механикой не поддержано.
    }
}
