namespace Game.Core.Base
{
    /// <summary>
    /// Здания города (GDD §7.1). Ядро (строит игрок за золото): Зал совета, Лазарет,
    /// Мастерская, Склад. Специальные (золото + строительный компонент, либо строит
    /// патрон): Рынок, Таверна, Храм, Укрепления, Оружейная, Лаборатория. У каждого —
    /// одна или несколько позиций (<see cref="AssignmentSlotDefinition"/>).
    /// </summary>
    public enum BaseSectionType
    {
        None = 0,

        // ---- Ядро (золото) ----
        Council = 1,    // Зал совета — действия совета
        Infirmary = 2,  // Лазарет — лечение раненых
        Workshop = 3,   // Мастерская — крафт
        Storehouse = 4, // Склад — вместимость

        // ---- Специальные (золото + строительный компонент / патрон) ----
        Market = 10,         // Рынок — доход золота + опции Торговли
        Tavern = 11,         // Таверна — рост населения + соц-события
        Temple = 12,         // Храм/Святилище — −Напряжение + лояльность
        Fortifications = 13, // Укрепления — −Напряжение + «Готовность»
        Armory = 14,         // Оружейная — доступ/скидка к продвинутому гиру
        Laboratory = 15      // Лаборатория — рост атрибутов / крафт аугмента
    }
}
