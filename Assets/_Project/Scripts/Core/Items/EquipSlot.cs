namespace Game.Core.Items
{
    /// <summary>
    /// Слот екіпірування. По одному предмету на слот (US-6.2: гір крутить
    /// числа, а не роздає здібності — здібності лишаються прогресією).
    /// Значення 0–2 — історичні й записані в старих сейвах: їх не можна
    /// переставляти. Нові слоти (Поправка №19.2: броня видима на моделі,
    /// «лялька» як у референсах) — лише в кінець.
    /// </summary>
    public enum EquipSlot
    {
        Weapon = 0,    // зброя — точність/шкода й подібні похідні; у бою — сама бойова зброя
        Armor = 1,     // броня тулуба (гамбезон, кольчуга, кіраса) — зазвичай +Armor/+MaxHp
        Accessory = 2, // аксесуар — точність/крит/бонуси до навичок тощо
        Head = 3,      // шолом
        Hands = 4,     // наручі, рукавиці
        Legs = 5,      // поножі
        Feet = 6,      // чоботи
        Offhand = 7    // щит або друга рука (недоступний із дворучною зброєю)
    }
}
