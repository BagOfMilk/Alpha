namespace Game.Core.Economy
{
    /// <summary>
    /// Ресурси гри. Валюта загону — золото; плюс ДВА компоненти, які
    /// видобуваються ТІЛЬКИ ззовні (вилазки, данжі, нагороди): місто їх не
    /// виробляє зовсім (Е6.2); їжа — окремо (Поправка №4).
    ///
    /// Поправка №12.5 (рішення власника 29.09.2026, «Давай 2»): один спільний
    /// Materials розділено на два компоненти, як у GDD (Е6.2, US-15.1), бо
    /// вони гейтять різне:
    /// <list type="bullet">
    /// <item><see cref="BuildComponent"/> — будівельний («Будматеріал»):
    /// спеціальні будівлі й апгрейди (US-7.2), разом із золотом.</item>
    /// <item><see cref="CraftComponent"/> — крафтовий («Сировина»): апгрейд і
    /// моди спорядження, витратники, аугмент (US-6.3, US-6.4).</item>
    /// </list>
    /// Кожен має кран і споживача (Статут MECH-03): різні точки вилазок і
    /// кімнати данжів дають різне, тож куди йти — рішення гравця.
    ///
    /// Значення 2 успадкував будівельний компонент від старого Materials:
    /// у старих зліпках «m:» — це колишні спільні матеріали, і вони
    /// відновлюються саме в будівельний (їхній головний споживач —
    /// будівництво). Значення 3 і 4 звільнені від Intel і Research і не
    /// перевикористовуються: діра в нумерації дешевша, ніж номер, який у
    /// старих нотатках значить одне, а в коді інше.
    /// </summary>
    public enum ResourceType
    {
        None = 0,
        Gold = 1,            // валюта загону: найм, ядро-будівлі, витратники
        BuildComponent = 2,  // будівельний компонент; джерело — лише ззовні
        Food = 5,            // прокорм поселення; єдине, що виробляє місто
        CraftComponent = 6   // крафтовий компонент; джерело — лише ззовні
        // Intel (3) і Research (4) прибрані: у GDD і поправках їх немає зовсім.
        // Medicine прибраний раніше: за US-4.3 лікування коштує днів, а не медикаментів.
    }
}
