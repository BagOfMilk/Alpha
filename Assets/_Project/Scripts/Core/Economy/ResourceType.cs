namespace Game.Core.Economy
{
    /// <summary>
    /// Ресурси гри. Валюта відряду — золото, плюс матеріали, які видобуваються
    /// ТІЛЬКИ ззовні: місто їх не виробляє зовсім (Е6.2).
    ///
    /// УВАГА, СВІДОМЕ СПРОЩЕННЯ. Е6.2 і US-15.1 вимагають ДВА компоненти —
    /// будівельний і крафтовий, і вони за GDD гейтять різне: будівництво (US-7.2) і
    /// крафт з аугментом (US-6.3, US-6.4). Тут поки один спільний Materials.
    /// Підстава — Додаток А, планка приймання: «базовий видобуток 1–2 матеріалів
    /// з вилазок». Другий компонент, заведений зараз, отримав би нуль
    /// споживачів — крафту немає — і завівся б мертвим. Розділяти разом із
    /// крафтом (Е6), не раніше; на карті це висить окремою карткою, а не
    /// видається за відповідність.
    ///
    /// Значення 3 і 4 звільнені від Intel і Research і не перевикористовуються:
    /// ні того, ні іншого немає ні в GDD, ні в поправках, а діра в нумерації
    /// дешевша, ніж номер, який у старих нотатках значить одне, а в коді
    /// інше.
    /// </summary>
    public enum ResourceType
    {
        None = 0,
        Gold = 1,       // валюта відряду: найм, ядро-будівлі, витратники
        Materials = 2,  // компонент будівництва і крафту; джерело — лише вилазки
        Food = 5        // прокорм поселення; єдине, що виробляє місто
        // Intel (3) і Research (4) прибрані: у GDD і поправках їх немає зовсім.
        // Medicine прибраний раніше: за US-4.3 лікування коштує днів, а не медикаментів.
    }
}
