namespace Game.Core.Economy
{
    /// <summary>
    /// Глобальные ресурсы базы. Производятся назначенными напарниками и тратятся
    /// на строительство, вербовку, исследования и снаряжение вылазок.
    /// </summary>
    public enum ResourceType
    {
        None = 0,
        Supplies = 1,   // припасы/деньги — универсальная валюта
        Materials = 2,  // материалы для строительства и крафта
        Intel = 3,      // разведданные — открывают точки вылазок и сюжет
        Research = 4,   // очки исследований
        Food = 5        // еда — содержание поселения
        // Medicine убран: по GDD US-4.3 лечение стоит дни, а не медикаменты,
        // а расходники — это предметы (Эпик 6), а не строка кошелька.
    }
}
