namespace Game.Core.Economy
{
    /// <summary>
    /// Ресурсы игры. Валюта отряда — золото, плюс материалы, которые добываются
    /// ТОЛЬКО снаружи: город их не производит вовсе (Э6.2).
    ///
    /// ВНИМАНИЕ, СОЗНАТЕЛЬНОЕ УПРОЩЕНИЕ. Э6.2 и US-15.1 требуют ДВА компонента —
    /// строительный и крафтовый, и они по GDD гейтят разное: стройку (US-7.2) и
    /// крафт с аугментом (US-6.3, US-6.4). Здесь пока один общий Materials.
    /// Основание — Приложение А, планка приёмки: «базовая добыча 1–2 материалов
    /// из вылазок». Второй компонент, заведённый сейчас, получил бы ноль
    /// потребителей — крафта нет — и завёлся бы мёртвым. Разделять вместе с
    /// крафтом (Э6), не раньше; на карте это висит отдельной карточкой, а не
    /// выдаётся за соответствие.
    ///
    /// Значения 3 и 4 освобождены от Intel и Research и не переиспользуются:
    /// ни того, ни другого нет ни в GDD, ни в поправках, а дырка в нумерации
    /// дешевле, чем номер, который в старых заметках значит одно, а в коде
    /// другое.
    /// </summary>
    public enum ResourceType
    {
        None = 0,
        Gold = 1,       // валюта отряда: найм, ядро-здания, расходники
        Materials = 2,  // компонент стройки и крафта; источник — только вылазки
        Food = 5        // прокорм поселения; единственное, что производит город
        // Intel (3) и Research (4) убраны: в GDD и поправках их нет вовсе.
        // Medicine убран раньше: по US-4.3 лечение стоит дни, а не медикаменты.
    }
}
