namespace Game.Core.Economy
{
    /// <summary>
    /// Ресурсы отряда (GDD §6/§15). Валюта — золото; плюс два компонента:
    /// строительный и крафтовый. Источник всех трёх — ТОЛЬКО вылазки/данжи +
    /// награды квестов (городского производства материалов нет; не-боевого пути
    /// нет — squad-loop кормит settlement-loop).
    /// </summary>
    public enum ResourceType
    {
        None = 0,
        Gold = 1,             // валюта отряда
        BuildingMaterial = 2, // строительный компонент — спец-здания и апгрейды зданий игрока
        CraftingMaterial = 3  // крафтовый компонент — апгрейды/моды гира, расходники, крафт аугмента
    }
}
