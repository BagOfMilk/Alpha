using System;

namespace Game.Core.Balance
{
    /// <summary>
    /// Числа «Пульсу світу» — накопичувачів тиску, що заміняють кидок кубика.
    ///
    /// ЯКІР: поріг 100 → днів до втручання ≈ 100 / Наполегливість.
    /// Наполегливість 10 = «приблизно раз на десять днів». Це якір для дизайнера;
    /// гравець замість числа отримує драбину передвісників.
    /// </summary>
    [Serializable]
    public sealed class PulseBalance
    {
        public int DefaultThreshold = 100;

        /// <summary>Частка заповнення, з якої йде передвісник 1-го ступеня (амбіент).</summary>
        public double Forewarn1At = 0.55;
        /// <summary>2-й ступінь: зобов'язаний назвати домен і місце.</summary>
        public double Forewarn2At = 0.80;
        /// <summary>3-й ступінь: названа близькість, але НІКОЛИ не точна доба.</summary>
        public double Forewarn3At = 0.95;

        public int MaxFiresPerDay = 1;
        /// <summary>Уночі інциденти щільніші (US-11.1).</summary>
        public int MaxFiresPerNight = 2;

        /// <summary>Стеля заряду, щоб простій не копичив нескінченну чергу.</summary>
        public int ChargeCapMultiplier = 2;

        /// <summary>
        /// ІНВАРІАНТ, а не порада: менше трьох одночасних накопичувачів —
        /// і повний детермінізм читається наскрізь. Перевіряється тестом.
        /// </summary>
        public int MinActiveTracks = 3;

        /// <summary>
        /// Вікно на реакцію між ПОЧУТИМ передвісником третього ступеня і
        /// кризою. Живе тут, а не в TensionBalance: читає його лише
        /// накопичувач, а константа зобов'язана лежати поряд зі своїм споживачем.
        /// </summary>
        public int CrisisGraceDays = 3;

        /// <summary>
        /// Скільки діб потрібно драбині кризи, щоб дійти від першого ступеня
        /// до третього у гравця, який спить: ступінь видається один за тик, а
        /// вночі чує тільки патруль, — отже, по одному за добу, третій —
        /// на другу добу після першого.
        ///
        /// Споживач — <see cref="World.PressureTrack"/>: після спрацьованої
        /// кризи драбина мовчить, поки до кінця відкату лишається більше, ніж
        /// <see cref="CrisisGraceDays"/> + це число. Інакше накопичувач,
        /// що копиться й під час відкату, знову доходив до третього ступеня через
        /// 3–5 діб після кризи, а наступний відкат кризи пускав лише через
        /// 30 — «скоро» висіло 25 діб (SETTLEMENT_LAYER §5.1, правило 4
        /// «Передвісник не бреше»). Дні криз від цього не змінюються: драбина
        /// встигає до кінця відкату.
        /// </summary>
        public int CrisisLadderLeadDays = 2;
    }
}
