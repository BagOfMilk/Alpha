using System;

namespace Game.Core.Balance
{
    /// <summary>
    /// Числа «Пульса мира» — накопителей давления, заменяющих бросок кубика.
    ///
    /// ЯКОРЬ: порог 100 → дней до вмешательства ≈ 100 / Настойчивость.
    /// Настойчивость 10 = «примерно раз в десять дней». Это якорь для дизайнера;
    /// игрок вместо числа получает лестницу предвестников.
    /// </summary>
    [Serializable]
    public sealed class PulseBalance
    {
        public int DefaultThreshold = 100;

        /// <summary>Доля заполнения, с которой идёт предвестник 1-й ступени (амбиент).</summary>
        public double Forewarn1At = 0.55;
        /// <summary>2-я ступень: обязана назвать домен и место.</summary>
        public double Forewarn2At = 0.80;
        /// <summary>3-я ступень: названа близость, но НИКОГДА не точный день.</summary>
        public double Forewarn3At = 0.95;

        public int MaxFiresPerDay = 1;
        /// <summary>Ночью инциденты кучнее (US-11.1).</summary>
        public int MaxFiresPerNight = 2;

        /// <summary>Потолок заряда, чтобы простой не копил бесконечную очередь.</summary>
        public int ChargeCapMultiplier = 2;

        /// <summary>
        /// ИНВАРИАНТ, а не совет: меньше трёх одновременных накопителей —
        /// и полный детерминизм читается насквозь. Проверяется тестом.
        /// </summary>
        public int MinActiveTracks = 3;

        /// <summary>
        /// Окно на реакцию между УСЛЫШАННЫМ предвестником третьей ступени и
        /// кризисом. Живёт здесь, а не в TensionBalance: читает его только
        /// накопитель, а константа обязана лежать рядом со своим потребителем.
        /// </summary>
        public int CrisisGraceDays = 3;

        /// <summary>
        /// Сколько суток нужно лестнице кризиса, чтобы дойти от первой ступени
        /// до третьей у игрока, который спит: ступень выдаётся одна за тик, а
        /// ночью слышит только патруль, — значит, по одной в сутки, третья —
        /// на вторые сутки после первой.
        ///
        /// Потребитель — <see cref="World.PressureTrack"/>: после сработавшего
        /// кризиса лестница молчит, пока до конца отката больше, чем
        /// <see cref="CrisisGraceDays"/> + это число. Иначе накопитель,
        /// копящий и во время отката, снова доходил до третьей ступени через
        /// 3–5 суток после кризиса, а следующий кризис откат пускал лишь через
        /// 30 — «скоро» висело 25 суток (SETTLEMENT_LAYER §5.1, правило 4
        /// «Предвестник не врёт»). Дни кризисов от этого не меняются: лестница
        /// успевает к концу отката.
        /// </summary>
        public int CrisisLadderLeadDays = 2;
    }
}
