using System;

namespace Game.Core.Balance
{
    /// <summary>
    /// Настройки слоя сигналов. Слой — часть системы, а не UI (Поправка №3.4):
    /// это единственный канал, через который игрок узнаёт о скрытых шкалах.
    /// </summary>
    [Serializable]
    public sealed class SignalBalance
    {
        /// <summary>Бюджет внимания игрока: больше — превращается в шум (риск N1).</summary>
        public int MaxSignalsPerDay = 4;

        /// <summary>Сколько слотов гарантированно уходит под «что изменилось со вчера».
        /// Прямое лекарство от «нет читаемого состояния».</summary>
        public int MinDeltaSlots = 1;

        /// <summary>Нет немого перехода полосы: смена полосы обязана дать сигнал.</summary>
        public bool ForceSignalOnBandChange = true;

        /// <summary>
        /// Сколько суток один и тот же ключ реплики не повторяется, если это не
        /// дельта. Ноль — выключено.
        ///
        /// ЗАЧЕМ ИМЕННО ТАК. Прогон кампании показал, что бюджет внимания не
        /// работает: в спокойном городе кандидатов МЕНЬШЕ, чем слотов, поэтому
        /// показывается всё подряд, и самый частый ключ появляется около двухсот
        /// раз за кампанию при трёх десятках уникальных на всю игру. Порядок
        /// отбора этого не лечит — лечить нечего, конкуренции за слот нет.
        /// Поэтому повтор именно ПОДАВЛЯЕТСЯ, а не задвигается в конец.
        ///
        /// Бюджет — это потолок, а не норма выработки: лучше одна строка, чем
        /// четыре одинаковых. Дельты и смена полосы под правило не попадают
        /// никогда, и последний сигнал не отбирается — немым день не станет.
        ///
        /// Число — плейсхолдер: сколько именно суток город молчит об одном и том
        /// же, решается плейтестом.
        /// </summary>
        public int TopicCooldownDays = 2;
    }
}
