using System;

namespace Game.Core.Balance
{
    /// <summary>
    /// Налаштування шару сигналів. Шар — частина системи, а не UI (Поправка №3.4):
    /// це єдиний канал, через який гравець дізнається про приховані шкали.
    /// </summary>
    [Serializable]
    public sealed class SignalBalance
    {
        /// <summary>Бюджет уваги гравця: більше — перетворюється на шум (ризик N1).</summary>
        public int MaxSignalsPerDay = 4;

        /// <summary>Скільки слотів гарантовано йде під «що змінилося з учора».
        /// Пряме лікування від «немає читабельного стану».</summary>
        public int MinDeltaSlots = 1;

        /// <summary>Немає німого переходу полоси: зміна полоси зобов'язана дати сигнал.</summary>
        public bool ForceSignalOnBandChange = true;

        /// <summary>
        /// Скільки діб той самий ключ репліки не повторюється, якщо це не
        /// дельта. Нуль — вимкнено.
        ///
        /// ЧОМУ САМЕ ТАК. Прогін кампанії показав, що бюджет уваги не
        /// працює: у спокійному місті кандидатів МЕНШЕ, ніж слотів, тому
        /// показується все підряд, і найчастіший ключ з'являється близько двохсот
        /// разів за кампанію при трьох десятках унікальних на всю гру. Порядок
        /// відбору цього не лікує — лікувати нічого, конкуренції за слот немає.
        /// Тому повтор саме ПРИДУШУЄТЬСЯ, а не відсувається в кінець.
        ///
        /// Бюджет — це стеля, а не норма виробітку: краще один рядок, ніж
        /// чотири однакових. Дельти і зміна полоси під правило не потрапляють
        /// ніколи, і останній сигнал не відбирається — німим день не стане.
        ///
        /// Число — плейсхолдер: скільки саме діб місто мовчить про одне й те
        /// саме, вирішується плейтестом.
        /// </summary>
        public int TopicCooldownDays = 2;
    }
}
