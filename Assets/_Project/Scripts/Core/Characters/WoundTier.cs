namespace Game.Core.Characters
{
    /// <summary>
    /// Тяжкість поранення (GDD US-4.3). Три тіри — три фіксовані терміни лікування
    /// в днях, а не пул очок: лікування коштує часу, а не ресурсу.
    ///
    /// Шрам навішується тільки Серйозним і вище (US-2.5, US-4.2) — легкі рани
    /// слідів не лишають.
    /// </summary>
    public enum WoundTier
    {
        None = 0,     // здоровий
        Light = 1,    // легке: короткий термін, шраму немає
        Serious = 2,  // серйозне: шрам
        Critical = 3  // тяжке: довгий термін і шрам
    }
}
