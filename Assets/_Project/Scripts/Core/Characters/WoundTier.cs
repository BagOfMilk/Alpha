namespace Game.Core.Characters
{
    /// <summary>
    /// Тяжесть ранения (GDD US-4.3). Три тира — три фиксированных срока лечения
    /// в днях, а не пул очков: лечение стоит время, а не ресурс.
    ///
    /// Шрам вешается только Серьёзным и выше (US-2.5, US-4.2) — лёгкие раны
    /// следов не оставляют.
    /// </summary>
    public enum WoundTier
    {
        None = 0,     // здоров
        Light = 1,    // лёгкое: короткий срок, шрама нет
        Serious = 2,  // серьёзное: шрам
        Critical = 3  // тяжёлое: длинный срок и шрам
    }
}
