namespace Game.Core.Checks
{
    /// <summary>
    /// Полоса исхода проверки (Поправка №3.7). Детерминированная проверка даёт
    /// не «успех/провал», а одну из четырёх полос по запасу над порогом.
    /// </summary>
    public enum OutcomeBand
    {
        /// <summary>Не хватило. Сюда же попадает незанятая позиция (US-8.2).</summary>
        Worst = 0,
        Base = 1,
        Good = 2,
        Best = 3
    }

    /// <summary>
    /// Форма подхода. Задаёт не число, а ФОРМУ лестницы исходов: вложение в
    /// социалку — это выбор профиля риска, а не пропуск.
    /// </summary>
    public enum ApproachForm
    {
        /// <summary>Нейтральный резолв (утилитарные навыки, разбор происшествия).</summary>
        Neutral = 0,
        /// <summary>Убеждение: поднимает пол, опускает потолок — страховка от хвостов.</summary>
        Persuade = 1,
        /// <summary>Запугивание: удлиняет оба хвоста.</summary>
        Intimidate = 2,
        /// <summary>Торговля: полосу не меняет, конвертирует запас в цену.</summary>
        Trade = 3
    }
}
