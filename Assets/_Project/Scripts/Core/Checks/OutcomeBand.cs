namespace Game.Core.Checks
{
    /// <summary>
    /// Полоса наслідку перевірки (Поправка №3.7). Детермінована перевірка дає
    /// не «успіх/провал», а одну з чотирьох полос за запасом над порогом.
    /// </summary>
    public enum OutcomeBand
    {
        /// <summary>Не вистачило. Сюди ж потрапляє незайнята позиція (US-8.2).</summary>
        Worst = 0,
        Base = 1,
        Good = 2,
        Best = 3
    }

    /// <summary>
    /// Форма підходу. Задає не число, а ФОРМУ драбини наслідків: вкладення в
    /// соціалку — це вибір профілю ризику, а не пропуск.
    /// </summary>
    public enum ApproachForm
    {
        /// <summary>Нейтральний резолв (утилітарні навички, розбір інциденту).</summary>
        Neutral = 0,
        /// <summary>Переконання: піднімає підлогу, опускає стелю — страховка від хвостів.</summary>
        Persuade = 1,
        /// <summary>Залякування: подовжує обидва хвости.</summary>
        Intimidate = 2,
        /// <summary>Торгівля: полосу не змінює, конвертує запас у ціну.</summary>
        Trade = 3
    }
}
