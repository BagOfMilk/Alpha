namespace Game.Core.Pressure
{
    /// <summary>
    /// Полоса «Напряжения» — единственное, что уходит наружу из скрытой шкалы.
    /// Само число игроку не показывается никогда (US-17.2), полоса же
    /// определяет, какие сигналы увидит игрок и какие инциденты доступны.
    /// </summary>
    public enum TensionBand
    {
        /// <summary>Спокойно: лавки открыты дотемна, дети во дворах.</summary>
        Calm = 0,
        /// <summary>Ропот: заколоченный ставень, спорят о ценах.</summary>
        Murmur = 1,
        /// <summary>Брожение: замолкают при твоём приближении, граффити.</summary>
        Ferment = 2,
        /// <summary>Накал: дневные ставни, патрули парами, часть NPC исчезла.</summary>
        Heat = 3,
        /// <summary>Излом: пустая площадь, оружие открыто, кризис на подходе.</summary>
        Fracture = 4
    }
}
