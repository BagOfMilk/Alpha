namespace Game.Core.Pressure
{
    /// <summary>
    /// Полоса «Напруги» — єдине, що йде назовні з прихованої шкали.
    /// Саме число гравцю не показується ніколи (US-17.2), полоса ж
    /// визначає, які сигнали побачить гравець і які інциденти доступні.
    /// </summary>
    public enum TensionBand
    {
        /// <summary>Спокій: крамниці відчинені дотемна, діти у дворах.</summary>
        Calm = 0,
        /// <summary>Ропіт: забиті віконниці, сперечаються про ціни.</summary>
        Murmur = 1,
        /// <summary>Бродіння: замовкають, коли ти наближаєшся, графіті.</summary>
        Ferment = 2,
        /// <summary>Розпал: денні віконниці, патрулі парами, частина NPC зникла.</summary>
        Heat = 3,
        /// <summary>Злам: порожня площа, зброя на видноті, криза на підході.</summary>
        Fracture = 4
    }
}
