using Game.Core.Pressure;

namespace Game.Core.Loop
{
    /// <summary>
    /// Голодний день піднімає Напругу (Поправка №4).
    ///
    /// Чому окремим кроком, а не прямо з BaseState: міський шар і модуль
    /// бази навмисно не знають один про одного. База виставляє факт голоду в
    /// контекст дня, а тиск наводить уже конвеєр — так само, як це зроблено
    /// з рештою драйверів.
    ///
    /// Стоїть перед тиком Напруги: сьогоднішній голод має увійти в сьогоднішню
    /// полосу, інакше таблиця інцидентів зважиться за вчорашньою обстановкою.
    ///
    /// Вночі не спрацьовує. Календарна доба — це дві фази, і без цього
    /// гейта один голодний день тиснув би двічі: темп «полоса за 25 голодних
    /// днів» перетворився б на 13, а помітити зсув можна було б, тільки звіривши
    /// числа з поправкою.
    /// </summary>
    public sealed class HungerStep : IDayStep
    {
        public int Order => DayStepOrder.Hunger;

        public void Execute(DayContext ctx)
        {
            if (ctx.IsNight) return;
            if (!ctx.IsHungry) return;
            TensionDrivers.Hunger(ctx.Tension, "hunger:day" + ctx.Day, ctx.Balance);
        }
    }
}
