namespace Game.Core.Loop
{
    /// <summary>
    /// Порт «у суток есть материальный итог»: кто-то произвёл, кто-то съел,
    /// кто-то подлечился.
    ///
    /// Зачем порт, а не прямая ссылка. Цикл поселения живёт в устаревшем слое
    /// (<c>Game.Core.Base</c>), завязанном на типы экономики и статов, которые
    /// будут переписаны. Городской слой обязан оставаться от них развязанным —
    /// это проверяет ArchitectureGuardTests. Через этот интерфейс конвейер
    /// знает ровно одно: сутки нужно прокрутить, — и не знает чем.
    /// </summary>
    public interface IDailyCycle
    {
        /// <summary>Прокрутить одни календарные сутки поселения.</summary>
        void RunDay();
    }
}
